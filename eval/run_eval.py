"""
Runs the RAG agent against golden_dataset_for_RAG_evaluation.xlsx and fills
in the "after running your chatbot" columns (G-R) automatically, then saves
a results copy. Columns S-V (Context Precision / Recall / Answer
Completeness / Faithfulness) are left as the workbook's own formulas -
they recompute from the numbers this script writes into K/L/M/N/O/P/Q.

Usage (from the project root, same place you'd run the app):
    python -m eval.run_eval
    python -m eval.run_eval --input path/to/golden_dataset.xlsx --output eval/golden_dataset_results.xlsx

What gets filled in, and how:

  G  Response generated by the chatbot
       -> agent_executor.invoke({"input": query})["output"], verbatim.

  H  Source(s) referenced by the chatbot
  I  Paragraph(s) referenced by the chatbot
       -> from rag/citations.py's extract_citations(): the passages whose
          exact [tag] the model actually copied into its final answer
          (used=True). H is the distinct source filenames, I is the full
          tags (source#p{chunk_index}), matching what the workbook asks for
          ("which document(s)" vs "which specific passage(s)").

  L  Number of paragraph(s) retrieved
  M  Number of relevant paragraph(s) retrieved
       -> L is every distinct chunk retrieve_documents returned this turn
          (used or not). M is a heuristic: how many of those retrieved
          chunks' source filenames appear in the golden "Citation sources"
          column (D) for that row. This is an approximation, not a human
          relevance judgement - the script flags it as such in Remarks so
          you know to spot-check it, per the workbook's own instruction
          that this scoring is meant to be a judgement call.

  J  Factually correct (Yes / No)
  O  Number of key points in the generated response
  P  Number of claims in the response supported by context
  Q  Number of claims in the generated response
  R  Remarks
       -> a single LLM-judge call (see _judge() below) compares the
          generated answer against the golden Expected answer (column F)
          and the actual retrieved context (all tool observations from
          this turn, not just the ones the model chose to cite), and
          returns a structured verdict. This is the same kind of judgement
          a human filling out this workbook would make by eye - it is a
          reasonable first pass, not a substitute for you reading the
          "genuinely ambiguous" row (S/N 4) yourself, since that one is
          explicitly testing whether the answer avoids overconfidence.

Requires OPENAI_API_KEY and DATABASE_URL/SUPABASE_DB_URL in .env, same as
the app itself - this drives the real agent_executor end to end, including
live Supabase queries and retrieval.
"""
import argparse
import json
import os
import re
import sys
import traceback
from pathlib import Path
from typing import Any, Dict, List, Tuple

from dotenv import load_dotenv

load_dotenv()  # before any project import - see agent.py's own note on this

import openpyxl
from langchain_openai import ChatOpenAI
from pydantic import BaseModel, Field

from rag.agent import agent_executor
from rag.citations import extract_citations

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = Path(__file__).resolve().parent / "golden_dataset_for_RAG_evaluation.xlsx"
DEFAULT_OUTPUT = Path(__file__).resolve().parent / "golden_dataset_results.xlsx"
SHEET_NAME = "Golden Dataset"
JUDGE_MODEL = os.getenv("EVAL_JUDGE_MODEL", "gpt-4o-mini")

REQUIRED_HEADERS = [
    "S/N",
    "Sample query",
    "Citation sources",
    "Expected answer",
    "Response generated by the chatbot",
    "Source(s) referenced by the chatbot",
    "Paragraph(s) referenced by the chatbot",
    "Factually correct (Yes / No)",
    "Number of paragraph(s) retrieved",
    "Number of relevant paragraph(s) retrieved",
    "Number of key points in the generated response",
    "Number of claims in the response supported by context",
    "Number of claims in the generated response",
    "Remarks",
]


class JudgeResult(BaseModel):
    factually_correct: bool = Field(
        description=(
            "True only if the generated answer agrees with the expected answer on every "
            "substantive fact it addresses (names, numbers, dates, yes/no conclusions). "
            "Different wording is fine; different facts or a different conclusion is not."
        )
    )
    key_points_generated: int = Field(
        description="Count of distinct factual points the generated answer makes, independent of the expected answer."
    )
    claims_total: int = Field(
        description="Total distinct factual claims made in the generated answer."
    )
    claims_supported: int = Field(
        description=(
            "Of those total claims, how many are backed by something present in the "
            "'Retrieved context' provided to you. A claim with no support in the retrieved "
            "context is a potential hallucination even if it happens to be true."
        )
    )
    remarks: str = Field(
        description=(
            "1-2 sentences: note any hallucination, missed nuance, wrong source, or - for "
            "an ambiguous question - whether the answer appropriately hedged instead of "
            "asserting a confident yes/no it wasn't entitled to. Empty string if nothing notable."
        )
    )


_judge_llm = ChatOpenAI(model=JUDGE_MODEL, temperature=0).with_structured_output(JudgeResult)

_JUDGE_PROMPT = """You are grading a wealth-management RAG chatbot's answer for an evaluation workbook.

Question asked:
{query}

Expected answer (golden reference):
{expected_answer}

Chatbot's generated answer:
{generated_answer}

Retrieved context actually available to the chatbot this turn (from its tools - some of \
this may be irrelevant noise, that's normal and part of what you're grading):
{retrieved_context}

Grade the chatbot's generated answer per the field descriptions. Be strict about \
claims_supported - only count a claim as supported if the retrieved context actually \
contains that fact, not just something adjacent to it."""


def _load_workbook(path: Path):
    wb = openpyxl.load_workbook(path, data_only=False)
    if SHEET_NAME not in wb.sheetnames:
        raise SystemExit(f"Sheet {SHEET_NAME!r} not found in {path} (found: {wb.sheetnames})")
    ws = wb[SHEET_NAME]

    header_row = next(ws.iter_rows(min_row=1, max_row=1))
    headers = {cell.value: cell.column for cell in header_row if cell.value}

    missing = [h for h in REQUIRED_HEADERS if h not in headers]
    if missing:
        raise SystemExit(f"Workbook is missing expected column(s): {missing}")

    return wb, ws, headers


def _parse_citation_sources(cell_text: str) -> List[str]:
    """
    "Citation sources" column looks like:
      "clients_portfolio.json (CL002); policy_investment_suitability.pdf (Section 4); ..."
    Returns just the filenames, lowercased, for fuzzy matching against what
    was actually retrieved.
    """
    if not cell_text:
        return []
    parts = re.split(r"[;\n]", cell_text)
    names = []
    for part in parts:
        name = part.strip()
        name = re.split(r"\s*\(", name)[0].strip()
        if name:
            names.append(name.lower())
    return names


def _run_agent(query: str) -> Tuple[str, List[Any]]:
    result = agent_executor.invoke({"input": query})
    return result["output"], result.get("intermediate_steps", [])


def _retrieved_context_text(intermediate_steps: List[Any]) -> str:
    """All raw tool output text from this turn - both retrieve_documents
    passages and query_client_database rows - so the judge can check
    groundedness against everything the agent actually saw, not just the
    document passages."""
    chunks = []
    for step in intermediate_steps:
        try:
            action, observation = step
        except (TypeError, ValueError):
            continue
        tool_name = getattr(action, "tool", "unknown_tool")
        chunks.append(f"--- {tool_name} output ---\n{observation}")
    return "\n\n".join(chunks) if chunks else "(no tool calls were made this turn)"


def _retrieval_counts(intermediate_steps: List[Any], expected_sources: List[str]) -> Tuple[int, int]:
    """
    L = distinct chunks retrieve_documents returned this turn.
    M = of those, how many have a source filename that appears in the
        golden "Citation sources" list for this question (heuristic - see
        module docstring).
    """
    citations = extract_citations(intermediate_steps, final_answer="")  # used-flag irrelevant here
    total = len(citations)
    relevant = sum(
        1 for c in citations if any(exp in c["source"].lower() for exp in expected_sources)
    )
    return total, relevant


def _judge(query: str, expected_answer: str, generated_answer: str, context_text: str) -> JudgeResult:
    prompt = _JUDGE_PROMPT.format(
        query=query,
        expected_answer=expected_answer,
        generated_answer=generated_answer,
        retrieved_context=context_text[:12000],  # keep the judge prompt bounded
    )
    return _judge_llm.invoke(prompt)


def run(input_path: Path, output_path: Path, limit: int = None) -> None:
    wb, ws, headers = _load_workbook(input_path)

    def col(name: str) -> int:
        return headers[name]

    rows_done = 0
    for row_idx in range(2, ws.max_row + 1):
        sn = ws.cell(row=row_idx, column=col("S/N")).value
        query = ws.cell(row=row_idx, column=col("Sample query")).value
        if sn is None or not query:
            continue
        if str(sn).strip().upper() == "EX":
            print(f"[row {row_idx}] skipping example row (S/N={sn!r})")
            continue
        if limit is not None and rows_done >= limit:
            break

        expected_answer = ws.cell(row=row_idx, column=col("Expected answer")).value or ""
        citation_sources_cell = ws.cell(row=row_idx, column=col("Citation sources")).value or ""
        expected_sources = _parse_citation_sources(citation_sources_cell)

        print(f"[row {row_idx}] S/N={sn} running agent on: {query!r}")
        try:
            generated_answer, intermediate_steps = _run_agent(query)
        except Exception:
            err = traceback.format_exc(limit=3)
            print(f"[row {row_idx}] AGENT ERROR:\n{err}")
            ws.cell(row=row_idx, column=col("Remarks")).value = f"ERROR running agent: {err[:500]}"
            rows_done += 1
            continue

        citations = extract_citations(intermediate_steps, generated_answer)
        used_citations = [c for c in citations if c["used"]]
        sources_cited = sorted({c["source"] for c in used_citations})
        paragraphs_cited = sorted({c["tag"] for c in used_citations})

        retrieved_total, retrieved_relevant = _retrieval_counts(intermediate_steps, expected_sources)
        context_text = _retrieved_context_text(intermediate_steps)

        try:
            verdict = _judge(query, expected_answer, generated_answer, context_text)
        except Exception:
            err = traceback.format_exc(limit=3)
            print(f"[row {row_idx}] JUDGE ERROR:\n{err}")
            verdict = JudgeResult(
                factually_correct=False,
                key_points_generated=0,
                claims_total=0,
                claims_supported=0,
                remarks=f"Judge call failed: {err[:300]}",
            )

        ws.cell(row=row_idx, column=col("Response generated by the chatbot")).value = generated_answer
        ws.cell(row=row_idx, column=col("Source(s) referenced by the chatbot")).value = (
            "; ".join(sources_cited) if sources_cited else "(none cited - client DB / no citation)"
        )
        ws.cell(row=row_idx, column=col("Paragraph(s) referenced by the chatbot")).value = (
            "; ".join(paragraphs_cited) if paragraphs_cited else ""
        )
        ws.cell(row=row_idx, column=col("Factually correct (Yes / No)")).value = (
            "Yes" if verdict.factually_correct else "No"
        )
        ws.cell(row=row_idx, column=col("Number of paragraph(s) retrieved")).value = retrieved_total
        ws.cell(row=row_idx, column=col("Number of relevant paragraph(s) retrieved")).value = retrieved_relevant
        ws.cell(row=row_idx, column=col("Number of key points in the generated response")).value = (
            verdict.key_points_generated
        )
        ws.cell(row=row_idx, column=col("Number of claims in the response supported by context")).value = (
            verdict.claims_supported
        )
        ws.cell(row=row_idx, column=col("Number of claims in the generated response")).value = (
            verdict.claims_total
        )
        remark = verdict.remarks or ""
        if retrieved_total and not expected_sources:
            remark = (remark + " [no golden 'Citation sources' parsed - M not comparable]").strip()
        ws.cell(row=row_idx, column=col("Remarks")).value = remark or "(auto-graded, no issues flagged)"

        print(
            f"[row {row_idx}] done - correct={verdict.factually_correct} "
            f"retrieved={retrieved_total}/{retrieved_relevant} "
            f"claims={verdict.claims_supported}/{verdict.claims_total}"
        )
        rows_done += 1

    output_path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(output_path)
    print(f"\nWrote {rows_done} graded row(s) to {output_path}")
    print(
        "Columns S-V (Context Precision/Recall, Answer Completeness, Faithfulness) are "
        "workbook formulas - open the file in Excel/Sheets and they'll compute from what "
        "this script just filled in."
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT, help="Path to golden_dataset_for_RAG_evaluation.xlsx")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="Where to write the graded copy")
    parser.add_argument("--limit", type=int, default=None, help="Only grade the first N golden rows (for a quick smoke test)")
    args = parser.parse_args()

    if not args.input.exists():
        raise SystemExit(f"Input workbook not found: {args.input}")

    run(args.input, args.output, limit=args.limit)


if __name__ == "__main__":
    main()